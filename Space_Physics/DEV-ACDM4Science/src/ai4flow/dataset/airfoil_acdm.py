# input normalisation
max_inputs_0 = 100.
max_inputs_1 = 38.12
max_inputs_2 = 1.0

# targets depend on normalization
max_targets_0 = 4.65
max_targets_1 = 2.04
max_targets_2 = 2.37

def normalize(data):
    """data is of shape (3, 128, 128)"""
    # print(data.shape, "xxx")
    # remove offset for p channel:
    data[3, :, :] -= np.mean(data[3, :, :])  # remove offset
    data[3, :, :] -= data[3, :, :] * data[5, :, :]  # pressure * mask

    # make dimension less:
    v_norm = (np.max(np.abs(data[0, :, :])) ** 2 + np.max(
                np.abs(data[1, :, :])) ** 2) ** 0.5
    data[3, :, :] /= v_norm ** 2
    data[4, :, :] /= v_norm
    data[5, :, :] /= v_norm

    # normalisation -- input
    data[0, :, :] *= (1.0 / max_inputs_0)
    data[1, :, :] *= (1.0 / max_inputs_1)

    # normalisation -- target
    data[3, :, :] *= (1.0 / max_targets_0)
    data[4, :, :] *= (1.0 / max_targets_1)
    data[5, :, :] *= (1.0 / max_targets_2)

    return data

class airfoilDataset(Dataset):
    """Dataset class for loading data from Vort2D data folder.

    Args:
        Dataset (_type_): _description_
    """

    def __init__(self, name:str, dataDir:str, sequenceLength:List[int], self_cond=False, rey=1000):
        # Params setup
        self.self_cond = self_cond
        self.transform = None
        self.name = name
        self.dataDir = dataDir
        self.seqLength = sequenceLength[0]
        self.seqSkip = sequenceLength[1]
        self.rey = rey
        self.cond_lists = []

        # load data
        print("Loading data from \t", self.dataDir)
        self.file_paths = []
        self.sample_paths = []
        for x in os.listdir(self.dataDir):
            file_path = os.path.join(
                self.dataDir, x
            )
            self.file_paths.append(file_path)
        self.file_paths = natsorted(self.file_paths)
        print(f"Loading completed. Files loaded: \t{len(self.file_paths)}")

        # random lists - generated by shuffule the original file_paths list. used to provide extra/conditional information
        for i in range(self.seqLength - 2):
            if self_cond:
                self.cond_lists.append(self.file_paths)
            else:
                self.cond_lists.append(random.sample(
                    self.file_paths,
                    len(self.file_paths)
                ))

        self.printDatasetInfo()
        return

    def __len__(self):
        return len(self.file_paths)

    def __getitem__(self, idx:int) -> dict:
        # get data
        samples = []
        for i in range(self.seqLength - 2):
            data_extra = normalize(np.load(self.cond_lists[i][idx])["a"])
            if self.self_cond:
                data_extra[-3:, :, :] = data_extra[0:3, :, :]
            samples.append(data_extra)

        data_cond = normalize(np.load(self.file_paths[idx])["a"])
        data_full = normalize(np.load(self.file_paths[idx])["a"])

        if not self.self_cond:
            data_cond[-3:, :, :] = np.zeros_like(data_cond[-3:, :, :])
        else:
            data_cond[-3:, :, :] = np.zeros_like(data_cond[-3:, :, :])
            # data_cond[-3:, :, :] = data_extra[0:3, :, :]

        samples.append(data_cond)
        samples.append(data_full)
        samples = [self.crop_img(s) for s in samples]
        data = np.stack(samples, axis=0)
        data = np.take(data, indices=[3, 4, 5, 0, 1, 2], axis=1)

        # get simParameters
        simParam = np.array([[self.rey] for i in range(3)], dtype=np.float32)

        # get allParameters
        allParam = {
            'Reynolds Number': np.array([self.rey, self.rey, self.rey], dtype=np.float32),
            'Mach Number': np.array([0., 0., 0.], dtype=np.float32),
            'Drag Coefficient': np.array([0., 0., 0.], dtype=np.float32),
            'Lift Coefficient': np.array([0., 0., 0.], dtype=np.float32),
            'Z Slice': np.array([0., 0., 0.], dtype=np.float32)
            }

        # get obstacle mask and perform cropping:
        obsMask = self.get_obsMask(data_full)
        obsMask = self.crop_img(obsMask).squeeze()

        res = {
            'data': data,
            'simParameters': simParam,
            'allParameters': allParam,
            'path': self.file_paths[idx],
            'obsMask': obsMask,
        }

        if self.transform:
            res = self.transform(res)
        else:
            print("WARNING: no data transformations are employed!")

        return res

    def get_obsMask(self, data):
        mask = (data[0, :, :] != 0).astype(np.int32)
        mask = mask[np.newaxis, :, :]
        return mask

    def printDatasetInfo(self):
        print("Dataset info detail:")
        print(f"\t Sequence length of each sample: {self.seqLength}")
        print(f"\t Sequence skiping samples of: {self.seqSkip}")

    def crop_img(self, img):
        """Corp a 256*256 image to 128*64

        Args:
            img (ndarray): the input image, of shape (channel, 256, 256)

        Returns:
            res (ndarray): croped version image, shape: (channel, 128, 64)
        """
        img = img[:, :, 32:96]
        return img

